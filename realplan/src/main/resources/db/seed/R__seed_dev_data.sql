    CROSS JOIN (
        VALUES
            (1, '알고리즘', 'QUANTITY_BASED', '알고리즘 실전 문제 풀이', 'HIGH', 'MEDIUM', 90, 120, 85, TIME '07:50', TIME '10:35'),
